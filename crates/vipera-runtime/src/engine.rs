    #[test]
    fn a_follow_up_turn_reuses_the_retained_prefix() {
        let mut engine = engine_with(greedy(), ToyForward::new(32), 64);
        let prompt = [1u32, 2, 3, 4, 5];
        let id = engine.admit(&prompt, 2).unwrap();
        let first = engine.generate(id).unwrap();
        assert_eq!(first.reused_tokens, 0);
        // A turn computes every prompt token plus the logits for each generated token except the
        // last one, which no later sample needs.
        assert_eq!(
            first.processed_tokens, 6,
            "5 prompt tokens and 1 decode step"
        );

        // The next turn repeats everything and adds two tokens.
        let mut follow_up = prompt.to_vec();
        follow_up.extend_from_slice(&first.tokens);
        follow_up.extend_from_slice(&[9, 8]);
        let reused = engine.append_prompt(id, &follow_up).unwrap();
        assert_eq!(reused, 7, "the whole retained context is a prefix");

        let second = engine.generate(id).unwrap();
        assert_eq!(second.reused_tokens, 7);
        assert_eq!(
            second.processed_tokens, 4,
            "the one generated token that had no KV state, the two new prompt tokens, and one \
             decode step; without reuse the nine-token prompt would be recomputed as well"
        );
    }

